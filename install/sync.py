"""Install the dialogue package into Claude Code, Codex and Cursor.

Usage: python install/sync.py [--home DIR] [--extra-rule FILE ...]

--home        install into DIR instead of the real home directory, to inspect the result first
--extra-rule  a personal always-on rule file (already loaded by Claude Code from ~/.claude/rules/)
              that should also reach Codex and Cursor; may be given more than once

Rerun after editing anything under core/, skills/ or shared/.
"""

from pathlib import Path
import argparse
import re
import shutil

PKG = Path(__file__).resolve().parent.parent
SKILLS = ["dialogue-relay", "dialogue-naming", "dialogue-think"]
NEEDS_CONCEPTS = ["dialogue-naming", "dialogue-think"]
# dialogue-think replaces these; leaving them installed would make two skills compete for the same requests.
REPLACED = ["socratic-thinking", "socratic-coding"]
BEGIN = "<!-- BEGIN dialogue: generated by dialogue/install/sync.py; edit the package, not this block -->"
END = "<!-- END dialogue -->"

parser = argparse.ArgumentParser()
parser.add_argument("--home", type=Path, default=Path.home())
parser.add_argument("--extra-rule", type=Path, action="append", default=[])
opts = parser.parse_args()
home = opts.home


def write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    # newline="" keeps LF; Python's default would write CRLF on Windows.
    path.write_text(text, encoding="utf-8", newline="")


def demote(text: str, levels: int) -> str:
    return re.sub(r"^(#{1,5}) ", lambda m: "#" * (len(m.group(1)) + levels) + " ", text, flags=re.M)


# 0. Skills ship their own copy of the concept library so a plugin or manual install works without this script.
concepts = (PKG / "shared/concepts.md").read_text(encoding="utf-8")
for name in NEEDS_CONCEPTS:
    copy = PKG / "skills" / name / "references/concepts.md"
    if not copy.exists() or copy.read_text(encoding="utf-8") != concepts:
        write(copy, concepts)
        print(f"refresh {copy.relative_to(PKG)}")

core = (PKG / "core/core.md").read_text(encoding="utf-8").strip()
chinese = demote((PKG / "core/chinese.md").read_text(encoding="utf-8").strip(), 1)
rule = core + "\n\n" + chinese + "\n"
extras = [p.read_text(encoding="utf-8").strip() for p in opts.extra_rule]

# 1. Claude Code always-on rule.
write(home / ".claude/rules/dialogue.md", "<!-- generated by dialogue/install/sync.py -->\n\n" + rule)
print(f"rule    {home / '.claude/rules/dialogue.md'}")

# 2. Skills for Claude Code and for agents that read ~/.agents/skills (Codex, Cursor); retire the skills they replace.
for root in (home / ".claude/skills", home / ".agents/skills", home / ".codex/skills"):
    for old in REPLACED:
        if (root / old).exists():
            dest = home / ".claude/skills-retired" / f"{old}-from-{root.parent.name.lstrip('.')}"
            dest.parent.mkdir(parents=True, exist_ok=True)
            shutil.move(str(root / old), str(dest))
            print(f"retired {root / old} -> {dest}")
for name in SKILLS:
    for root in (home / ".claude/skills", home / ".agents/skills"):
        shutil.copytree(PKG / "skills" / name, root / name, dirs_exist_ok=True)
print(f"skills  {', '.join(SKILLS)} -> ~/.claude/skills, ~/.agents/skills")

# 3. Codex has no rule directory, so the always-on text lives in a marked block of the global AGENTS.md.
agents_md = home / ".codex/AGENTS.md"
block = "\n\n".join([BEGIN, demote(rule, 1).strip()] + [demote(e, 1) for e in extras] + [END])
current = agents_md.read_text(encoding="utf-8") if agents_md.exists() else ""
pattern = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.S)
updated = pattern.sub(lambda _: block, current) if pattern.search(current) else (current.rstrip() + "\n\n" + block + "\n").lstrip()
write(agents_md, updated)
size = len(updated.encode("utf-8"))
print(f"codex   {agents_md} ({size} bytes{'; over the 32 KiB default project_doc_max_bytes' if size > 32 * 1024 else ''})")

# 4. Cursor keeps User Rules only in its settings UI, so write a paste-ready copy.
export = home / ".claude/exports/cursor-user-rules.md"
cursor_text = "\n\n".join([rule.strip()] + extras) + "\n"
previous = export.read_text(encoding="utf-8") if export.exists() else None
write(export, cursor_text)
print(f"cursor  {export} ({'unchanged' if previous == cursor_text else 'CHANGED: paste into Cursor > Settings > Rules > User Rules'})")

# 5. The authoring linter is useful for any skill or rule file, so it goes next to the other user scripts.
write(home / ".claude/scripts/lint-spec.mjs", (PKG / "tools/lint-spec.mjs").read_text(encoding="utf-8"))
print(f"lint    {home / '.claude/scripts/lint-spec.mjs'}")

# 6. Hook scripts are copied next to the other user hooks; settings.json is the user's to review, so only print the entries.
# session-core.mjs is for plugin installs only: here the rule file above already loads every session.
hooks = home / ".claude/hooks/dialogue/prompt-signals.mjs"
write(hooks, (PKG / "hooks/prompt-signals.mjs").read_text(encoding="utf-8"))
term = home / ".claude/skills/dialogue-naming/scripts/term-check.mjs"
print("hooks   add to settings.json if wanted:")
print(f'  UserPromptSubmit: node "{hooks.as_posix()}"')
print(f'  Stop:             node "{term.as_posix()}" --hook-stop')
